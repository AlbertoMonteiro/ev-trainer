// Downloads the Generation III FireRed/LeafGreen sprites (#1–386) from PokeAPI/sprites, pinned to a
// commit so the result is reproducible, into src/EvTrainer.Web/wwwroot/sprites/{dex}.png.
// Run from the repository root:  dotnet run scripts/DownloadSprites.cs
#:property TreatWarningsAsErrors=false
#:property PublishAot=false

using System.Buffers.Binary;

const int LastSpecies = 386;
const int ExpectedSize = 64;
const string Commit = "35fdbe9bdec8f519f882c3edc3c0185f08af4d86";
const string Folder = "sprites/pokemon/versions/generation-iii/firered-leafgreen";
const string OutputDir = "src/EvTrainer.Web/wwwroot/sprites";
ReadOnlySpan<byte> pngSignature = [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A];
var signature = pngSignature.ToArray();

Directory.CreateDirectory(OutputDir);
using var http = new HttpClient
{
    BaseAddress = new Uri($"https://raw.githubusercontent.com/PokeAPI/sprites/{Commit}/{Folder}/"),
    Timeout = TimeSpan.FromSeconds(60),
};
http.DefaultRequestHeaders.UserAgent.ParseAdd("ev-trainer-sprite-downloader/1.0");

var errors = new List<string>();
long totalBytes = 0;
using var throttle = new SemaphoreSlim(8);
await Task.WhenAll(Enumerable.Range(1, LastSpecies).Select(async dex =>
{
    await throttle.WaitAsync();
    try
    {
        var bytes = await http.GetByteArrayAsync($"{dex}.png");
        if (bytes.Length < 24 || !bytes.AsSpan(0, 8).SequenceEqual(signature))
        {
            lock (errors) errors.Add($"#{dex}: not a PNG");
            return;
        }

        // IHDR is the first chunk: width and height are big-endian at offsets 16 and 20.
        var width = BinaryPrimitives.ReadInt32BigEndian(bytes.AsSpan(16, 4));
        var height = BinaryPrimitives.ReadInt32BigEndian(bytes.AsSpan(20, 4));
        if (width != ExpectedSize || height != ExpectedSize)
        {
            lock (errors) errors.Add($"#{dex}: {width}x{height}, expected {ExpectedSize}x{ExpectedSize}");
            return;
        }

        await File.WriteAllBytesAsync(Path.Combine(OutputDir, $"{dex}.png"), bytes);
        Interlocked.Add(ref totalBytes, bytes.Length);
    }
    catch (HttpRequestException e)
    {
        lock (errors) errors.Add($"#{dex}: {e.Message}");
    }
    finally
    {
        throttle.Release();
    }
}));

if (errors.Count > 0)
{
    Console.Error.WriteLine(string.Join(Environment.NewLine, errors.Order()));
    return 1;
}

File.WriteAllText(Path.Combine(OutputDir, "CREDITS.md"), $"""
    # Sprites

    Generation III (Pokémon FireRed / LeafGreen) front sprites #1–386.

    - Source: https://github.com/PokeAPI/sprites/tree/{Commit}/{Folder}
    - Commit: `{Commit}`
    - Generated by `scripts/DownloadSprites.cs` (`dotnet run scripts/DownloadSprites.cs`).

    Pokémon images © The Pokémon Company (Nintendo / Creatures Inc. / GAME FREAK inc.).
    The PokeAPI/sprites repository is distributed under CC0 1.0 Universal; that license does not
    cover the copyright of the images themselves. Used here in a free, non-commercial fan tool.

    """.Replace("\r\n", "\n"));

Console.WriteLine($"sprites: {LastSpecies} files, {totalBytes / 1024.0:F0} KB");
return 0;
